package io.github.stigjohnny.docs.site;

import io.github.stigjohnny.docs.Html;
import io.github.stigjohnny.docs.markdown.RenderedMarkdown;
import io.github.stigjohnny.docs.repo.AllowlistEntry;
import io.github.stigjohnny.docs.repo.Sources;
import java.util.ArrayList;
import java.util.List;

/**
 * The third-party notices: the repository's own THIRD-PARTY-NOTICES.md, rendered as it is, with what the site serves
 * of it. It covers Mermaid's MIT licence and the components bundled inside the file (condition 8 of
 * security/reviews/vendored-js--mermaid--11.17.2.md).
 */
final class NoticesPage {

    static final String PAGE = "trust/third-party-notices.html";
    static final String SOURCE = "THIRD-PARTY-NOTICES.md";

    private NoticesPage() {
    }

    static SitePage of(SiteContext context) {
        Sources sources = context.sources();
        AllowlistEntry mermaid = SiteBuilder.mermaidEntry(sources);
        String notices = Sources.text(sources.repo(), SOURCE);
        RenderedMarkdown rendered = context.render(notices, SOURCE, PAGE, true);
        String body = "<h2 id=\"served-here\">What this site serves</h2>\n<dl class=\"facts\">\n"
                + fact("File", "<code>" + Html.escape(SiteBuilder.MERMAID) + "</code>, the unmodified Mermaid "
                        + Html.escape(mermaid.version()) + " bundle, loaded on the four diagram pages only")
                + fact("SHA-256", "<code class=\"digest\">" + Html.escape(mermaid.sha256()) + "</code>, checked "
                        + "against the allowlist before the build copies it")
                + fact("This site's own files", "The pages, the stylesheet and the script are generated by this "
                        + "repository's documentation tool. The site loads no web fonts, no analytics and nothing "
                        + "from another origin.")
                + "</dl>\n" + rendered.html();
        context.map().anchor(PAGE, "served-here");
        List<SitePage.Contents> contents = new ArrayList<>();
        contents.add(new SitePage.Contents("served-here", "What this site serves"));
        contents.addAll(rendered.headings().stream().filter(h -> h.level() == 2)
                .map(h -> new SitePage.Contents(h.id(), h.text())).toList());
        return new SitePage(PAGE, "Third-party notices", "Third-party notices", SiteSection.TRUST, "The licences of "
                + "the third-party material in the repository, and the one third-party file this site serves.",
                new StatusPanel(Statuses.design("accepted", "Mermaid " + mermaid.version() + " is reviewed and "
                        + "approved with conditions (" + mermaid.reviewRecord() + ")."),
                        Badge.NEUTRAL.html("Not applicable") + " Notices describe no capability.",
                        Badge.NEUTRAL.html("Checked") + " The build checks the bundle's SHA-256 against the "
                                + "allowlist before copying it."),
                contents, body, List.of(new SitePage.Related(AllowlistPage.PAGE, "Dependency allowlist")),
                SOURCE + " and " + mermaid.reviewRecord(), false);
    }

    private static String fact(String term, String description) {
        return "<div><dt>" + Html.escape(term) + "</dt><dd>" + description + "</dd></div>\n";
    }
}
