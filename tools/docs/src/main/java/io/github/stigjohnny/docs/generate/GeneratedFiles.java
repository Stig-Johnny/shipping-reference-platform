package io.github.stigjohnny.docs.generate;

import io.github.stigjohnny.docs.DocsException;
import io.github.stigjohnny.docs.check.Consistency;
import io.github.stigjohnny.docs.mermaid.MermaidDiagram;
import io.github.stigjohnny.docs.repo.Sources;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.LinkOption;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.stream.Stream;

/**
 * The committed generated Markdown: {@code docs/architecture/}, {@code BRAIN.md} and {@code docs/brain/}. Generation
 * is deterministic (sorted inputs, no clock, no environment), so it can be compared byte for byte with what is
 * committed; {@link #compare} is what {@code :tools:docs:checkGenerated} runs.
 */
public final class GeneratedFiles {

    private GeneratedFiles() {
    }

    /** Checks the sources, then produces every generated file, keyed by repository-relative path. */
    public static Map<String, String> generate(Sources sources) {
        Consistency.check(sources);
        List<MermaidDiagram> diagrams = Diagrams.of(sources.workspace(), sources.elementStatus());
        Map<String, String> files = new TreeMap<>();
        files.putAll(ArchitecturePages.generate(sources, diagrams));
        files.putAll(Brains.generate(sources));
        for (Map.Entry<String, String> file : files.entrySet()) {
            if (!file.getValue().contains(ArchitecturePages.NOTICE)) {
                throw new DocsException(file.getKey() + " lacks the notice '" + ArchitecturePages.NOTICE + "'");
            }
        }
        return files;
    }

    /** Every difference between the generated files and the repository: missing, changed or stale files. */
    public static List<String> compare(Map<String, String> expected, Path repo) {
        List<String> problems = new ArrayList<>();
        for (Map.Entry<String, String> file : expected.entrySet()) {
            Path path = repo.resolve(file.getKey());
            if (!Files.isRegularFile(path)) {
                problems.add(file.getKey() + " is missing");
                continue;
            }
            byte[] actual = Sources.bytes(repo, file.getKey());
            byte[] wanted = file.getValue().getBytes(StandardCharsets.UTF_8);
            if (!java.util.Arrays.equals(actual, wanted)) {
                problems.add(file.getKey() + " differs from what the sources generate, first at line "
                        + firstDifferentLine(new String(actual, StandardCharsets.UTF_8), file.getValue()));
            }
        }
        for (String directory : Sources.GENERATED_DIRS) {
            for (String path : entries(repo, directory)) {
                Path entry = repo.resolve(path);
                if (Files.isSymbolicLink(entry)) {
                    problems.add(path + " is a link; a generated directory holds generated files only");
                } else if (Files.isRegularFile(entry, LinkOption.NOFOLLOW_LINKS) && !expected.containsKey(path)) {
                    problems.add(path + " is not generated by anything; remove it");
                }
            }
        }
        return problems;
    }

    /**
     * Every entry under a generated directory, files, directories and links alike, without following any link,
     * repository-relative and sorted. The directory itself must not be a link.
     */
    static List<String> entries(Path repo, String directory) {
        Path root = repo.resolve(directory);
        if (Files.isSymbolicLink(root)) {
            throw new DocsException(directory + " is a link; a generated directory holds generated files only");
        }
        if (!Files.isDirectory(root, LinkOption.NOFOLLOW_LINKS)) {
            return List.of();
        }
        try (Stream<Path> walk = Files.walk(root)) {
            return walk.filter(path -> !path.equals(root))
                    .map(path -> repo.relativize(path).toString().replace('\\', '/')).sorted().toList();
        } catch (IOException | UncheckedIOException e) {
            throw new DocsException(directory + ": cannot be listed (" + e.getClass().getSimpleName() + ")", e);
        }
    }

    /** Writes the generated files and removes stale ones from the generated directories. */
    public static void write(Map<String, String> files, Path repo) {
        try {
            for (String directory : Sources.GENERATED_DIRS) {
                for (String path : entries(repo, directory)) {
                    Path entry = repo.resolve(path);
                    boolean stale = Files.isSymbolicLink(entry)
                            || (Files.isRegularFile(entry, LinkOption.NOFOLLOW_LINKS) && !files.containsKey(path));
                    if (stale) {
                        Files.delete(entry);
                    }
                }
            }
            for (Map.Entry<String, String> file : new TreeMap<>(files).entrySet()) {
                Path path = repo.resolve(file.getKey());
                Path parent = path.getParent();
                if (parent != null) {
                    Files.createDirectories(parent);
                }
                Files.writeString(path, file.getValue(), StandardCharsets.UTF_8);
            }
        } catch (IOException e) {
            throw new DocsException("the generated files cannot be written: " + e.getClass().getSimpleName(), e);
        }
    }

    private static int firstDifferentLine(String actual, String expected) {
        String[] a = actual.split("\n", -1);
        String[] b = expected.split("\n", -1);
        for (int i = 0; i < Math.min(a.length, b.length); i++) {
            if (!a[i].equals(b[i])) {
                return i + 1;
            }
        }
        return Math.min(a.length, b.length) + 1;
    }
}
